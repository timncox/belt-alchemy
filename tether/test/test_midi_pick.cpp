/* what the ST host keeps: the first two interface descriptors met */
static int st_sees_midi(const uint8_t* c, unsigned len)
{
    unsigned p = c[0], n = 0;
    while (p + 2 <= len && n < 2)
    {
        if (c[p + 1] == 4) { if (c[p + 5] == 1 && c[p + 6] == 3) return 1; n++; }
        p += c[p];
    }
    return 0;
}

int main()
{
    midi_pick_t m;
    printf("midi_itf_pick\n");
    CHECK(sizeof fm1 == 252 && (fm1[2] | fm1[3] << 8) == 252, "FM-1 descriptor: %u bytes, fits the 256-byte read", (unsigned)sizeof fm1);
    CHECK(!st_sees_midi(fm1, sizeof fm1), "FM-1: the ST host's two entries hold no MIDI (why B3 stayed amber)");
    CHECK(midi_itf_pick(fm1, sizeof fm1, &m), "FM-1: MIDI streaming found");
    CHECK(m.itf[2] == 3 && m.itf[4] == 2 && m.neps == 2, "FM-1: interface %u, %u bulk endpoints", m.itf[2], m.neps);
    CHECK(m.ep[0][2] == 0x01 && m.ep[1][2] == 0x81 && m.ep[1][4] == 64, "FM-1: endpoints %02x and %02x, 64 bytes", m.ep[0][2], m.ep[1][2]);
    CHECK(sizeof smk37 == 178 && (smk37[2] | smk37[3] << 8) == 178, "SMK-37 descriptor: %u bytes, fits the 256-byte read", (unsigned)sizeof smk37);
    CHECK(st_sees_midi(smk37, sizeof smk37), "SMK-37: MIDI is the ST host's second entry, opened without moving it");
    CHECK(midi_itf_pick(smk37, sizeof smk37, &m) && m.itf[2] == 1 && m.neps == 2, "SMK-37: MIDI streaming is interface %u, %u bulk endpoints", m.itf[2], m.neps);
    CHECK(m.ep[0][2] == 0x01 && m.ep[1][2] == 0x81 && m.ep[1][4] == 64, "SMK-37: endpoints %02x and %02x, 64 bytes", m.ep[0][2], m.ep[1][2]);
    CHECK(smk37[7] == 0x80 && smk37[8] == 50, "SMK-37: asks for 100 mA from the port (the Lab gives none)");
    CHECK(st_sees_midi(plain, sizeof plain), "plain controller: the ST host already sees its MIDI");
    CHECK(midi_itf_pick(plain, sizeof plain, &m) && m.itf[2] == 1 && m.neps == 2, "plain controller: interface %u", m.itf[2]);
    CHECK(!midi_itf_pick(hub, sizeof hub, &m), "hub: no MIDI, left alone");
    CHECK(!midi_itf_pick(fm1, 200, &m), "FM-1 cut at 200 bytes: no bulk IN, not taken");
    uint8_t bad[sizeof fm1];
    memcpy(bad, fm1, sizeof fm1);
    bad[9] = 0;   /* a zero-length descriptor */
    CHECK(!midi_itf_pick(bad, sizeof bad, &m), "a zero-length descriptor stops the walk");
    printf(fails ? "FAILED %d\n" : "all passed\n", fails);
    return fails != 0;
}
